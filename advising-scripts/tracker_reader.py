# tracker_reader.py — read an existing tracker back in as plain data.
# Usage: imported by transcript_to_tracker.py; not run directly.
#
# This is the half of "merge" that recovers the advisor's work. A tracker
# holds two quite different kinds of information:
#
#   from the transcript — Term, Course, Title, CH, Gr.
#   from the ADVISOR    — Cat., Ovr., Notes, the gpa1/gpa2 flags, the track,
#                         and the constraint attestations
#
# Only the first kind can be regenerated from the PDF. The second represents
# real judgement that must survive every re-run, so it is read out here, merged
# with the new transcript, and written into a freshly generated workbook.
#
# Note that we only ever read LITERAL cells — the Courses table, the identity
# cells and the constraint ticks. Every formula cell in a tracker is
# regenerated from the requirements file, so a workbook that has never been
# opened in Excel (and therefore has no cached formula results) reads back
# perfectly well.

from pathlib import Path

import openpyxl

CAT_PREFIX = "Cat. "

# An ad hoc tracker — one generated with no requirements file — labels its
# category column with the bare "Cat.", because the categories in it are the
# advisor's own rather than a requirements file's. It reads back under the key
# "cat", which is deliberately NOT one of the "cat_<label>" keys: those are
# matched against an edition, and this one has no edition to match.
AD_HOC_CAT_COLUMN = "Cat."
AD_HOC_CAT_KEY = "cat"


class TrackerReadError(Exception):
    """Raised when a file doesn't look like a tracker we generated."""


def _text(value):
    if value is None:
        return ""
    return str(value).strip()


def _flag(value):
    """Read a gpa flag cell, which may hold a boolean or the text "TRUE"."""
    if isinstance(value, bool):
        return value
    return _text(value).upper() == "TRUE"


# The Ovr. column originally used "yes"/"no", which was ambiguous about what
# question was being answered. Trackers generated before the change are
# migrated on read so an advisor's existing overrides survive.
LEGACY_OVERRIDES = {"yes": "incl.", "no": "excl."}


def _override(value):
    text = _text(value)
    return LEGACY_OVERRIDES.get(text.lower(), text)


def _number(value):
    if value is None or _text(value) == "":
        return ""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return _text(value)
    return int(number) if number == int(number) else number


def _find_header_row(sheet):
    """Locate the Courses table header by looking for its first column."""
    for row in range(1, min(sheet.max_row, 40) + 1):
        if _text(sheet.cell(row=row, column=1).value) == "Term":
            return row
    raise TrackerReadError(
        "could not find the Courses table — no 'Term' header cell in the "
        "first 40 rows. Is this a tracker generated by this tool?"
    )


def read_tracker(path):
    """Read a tracker workbook.

    Returns a dict with:
        student     {'name', 'id'}
        track       the track selected in B3
        rows        list of course dicts, including advisor-owned fields
        constraints {block label: [bool, ...]}  (best effort)
    """
    path = Path(path)
    if not path.exists():
        raise TrackerReadError("No such tracker file: " + str(path))

    workbook = openpyxl.load_workbook(str(path), data_only=True)
    if "Tracker" in workbook.sheetnames:
        sheet = workbook["Tracker"]
    else:
        sheet = workbook.worksheets[0]

    header_row = _find_header_row(sheet)

    headings = {}
    for column in range(1, sheet.max_column + 1):
        name = _text(sheet.cell(row=header_row, column=column).value)
        if name:
            headings[name] = column

    for needed in ("Term", "Course", "Title", "CH", "Gr."):
        if needed not in headings:
            raise TrackerReadError(
                "Courses table is missing the " + repr(needed) + " column."
            )

    cat_columns = {name: column for name, column in headings.items()
                   if name.startswith(CAT_PREFIX)}
    # "Cat." does not start with "Cat. ", so the two cannot collide — but be
    # explicit about it rather than leaving it to a trailing space nobody can
    # see in a diff.
    ad_hoc_cat_column = headings.get(AD_HOC_CAT_COLUMN)

    rows = []
    for excel_row in range(header_row + 1, sheet.max_row + 1):
        def cell(name):
            column = headings.get(name)
            if column is None:
                return None
            return sheet.cell(row=excel_row, column=column).value

        term = _text(cell("Term"))
        course = _text(cell("Course"))
        title = _text(cell("Title"))

        # Spare rows at the foot of the table carry only their FALSE flags.
        if not term and not course and not title:
            continue

        row = {
            "term": term,
            "course": course,
            "title": title,
            "hours": _number(cell("CH")),
            "grade": _text(cell("Gr.")),
            "ovr": _override(cell("Ovr.")),
            "notes": _text(cell("Notes")),
            "gpa1": _flag(cell("gpa1")),
            "gpa2": _flag(cell("gpa2")),
        }
        for name, column in cat_columns.items():
            label = name[len(CAT_PREFIX):]
            row["cat_" + label] = _text(
                sheet.cell(row=excel_row, column=column).value)
        if ad_hoc_cat_column is not None:
            row[AD_HOC_CAT_KEY] = _text(
                sheet.cell(row=excel_row, column=ad_hoc_cat_column).value)
        rows.append(row)

    student = {
        "name": _text(sheet["B1"].value),
        "id": _text(sheet["B2"].value),
    }
    track = _text(sheet["B3"].value)

    return {
        "student": student,
        "track": track,
        "rows": rows,
        "constraints": _read_constraints(sheet),
    }


def _read_constraints(sheet):
    """Best-effort read of the advisor's constraint tick-boxes.

    Keyed by the edition label taken from the "DEGREE REQUIREMENTS (x)"
    heading above each block. If the layout has shifted, this quietly returns
    nothing rather than failing the whole read — an unticked box is a far
    smaller loss than a merge that refuses to run.
    """
    result = {}
    try:
        for row in range(1, min(sheet.max_row, 80) + 1):
            for column in range(1, sheet.max_column + 1):
                if _text(sheet.cell(row=row, column=column).value) \
                        != "CONSTRAINTS":
                    continue
                label = _block_label(sheet, column)
                ticks = []
                probe = row + 1
                while probe <= sheet.max_row:
                    number = sheet.cell(row=probe, column=column).value
                    if number is None or _text(number) == "":
                        break
                    ticks.append(_flag(
                        sheet.cell(row=probe, column=column + 3).value))
                    probe += 1
                if label:
                    result[label] = ticks
    except Exception:
        return {}
    return result


def _block_label(sheet, column):
    """Recover "2020" from a "DEGREE REQUIREMENTS (2020)" heading."""
    for row in range(1, 10):
        text = _text(sheet.cell(row=row, column=column).value)
        if text.startswith("DEGREE REQUIREMENTS (") and text.endswith(")"):
            return text[len("DEGREE REQUIREMENTS ("):-1]
    return ""
